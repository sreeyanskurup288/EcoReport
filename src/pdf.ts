import { jsPDF } from 'jspdf'
import type { Report } from './types'

function writeReport(pdf: jsPDF, report: Report, y: number) {
  const line = (label: string, value: string) => {
    pdf.setFont('helvetica', 'bold')
    pdf.text(label, 18, y)
    pdf.setFont('helvetica', 'normal')
    const lines = pdf.splitTextToSize(value || 'Not provided', 150)
    pdf.text(lines, 62, y)
    y += Math.max(7, lines.length * 5)
  }
  pdf.setFontSize(16)
  pdf.setTextColor(22, 68, 51)
  pdf.text(`EcoReport · ${report.id}`, 18, y)
  y += 12
  pdf.setFontSize(10)
  pdf.setTextColor(20, 36, 28)
  line('Issue:', `${report.type} (${report.severity})`)
  line('Status:', report.status)
  line('Reporter:', report.submitter || 'Community member')
  line('Date:', new Date(report.created_at).toLocaleDateString('en-IN'))
  line('Location:', report.location)
  line('Google Maps:', report.gmaps_url || 'Not provided')
  y += 3
  pdf.setFont('helvetica', 'bold')
  pdf.text('Description:', 18, y)
  y += 6
  pdf.setFont('helvetica', 'normal')
  pdf.text(pdf.splitTextToSize(report.description, 170), 18, y)
  return y + Math.max(14, pdf.splitTextToSize(report.description, 170).length * 5)
}

export function exportReportPdf(report: Report) {
  const pdf = new jsPDF()
  writeReport(pdf, report, 24)
  pdf.setFontSize(8)
  pdf.setTextColor(100, 120, 108)
  pdf.text('Generated by EcoReport', 18, 285)
  pdf.save(`${report.id}-ecoreport.pdf`)
}

export function exportReportsPdf(reports: Report[], title = 'EcoReport reports') {
  const pdf = new jsPDF()
  reports.forEach((report, index) => {
    if (index > 0) pdf.addPage()
    pdf.setFontSize(11)
    pdf.setTextColor(100, 120, 108)
    pdf.text(title, 18, 14)
    writeReport(pdf, report, 28)
  })
  if (!reports.length) pdf.text('No reports to export.', 18, 28)
  pdf.save('ecoreport-reports.pdf')
}
